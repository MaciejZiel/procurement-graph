export function t(value: string, language: Language): string {
  if (language === "en") return value;
  if (value.startsWith("API returned status ")) return `API odpowiedziało kodem ${value.slice("API returned status ".length)}`;
  return polish[value] ?? value;
}

export function localizeSource(value: string, language: Language): string {
  if (language === "en") return value;
  const notice = value.match(/^BZP notice (.+)$/);
  if (notice) return `Ogłoszenie BZP ${notice[1]}`;
  return t(value, language);
}
